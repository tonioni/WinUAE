void host_keymap_init(host_keymap *out, const int *native, bool pc_pause)
{
    const uae_input_device_kbr_default *sources[] = {defaults_0, defaults_1};
    memset(out, 0, sizeof *out);
    for (int table = 0; table < 2; table++) {
	int count = 0;
	for (const auto *entry = sources[table]; entry->scancode >= 0; entry++) {
	    int key = entry->scancode;
	    if (native[key] < 0 || (table == 1 && key == HOST_KEY_PAUSE && !pc_pause))
		continue;
	    out->table[table][count] = *entry;
	    out->table[table][count++].scancode = native[key];
	}
	out->table[table][count].scancode = -1;
    }
    out->translations[0] = out->table[0];
    out->translations[1] = out->translations[2] = out->table[1];
    for (int map = 0; map < 11; map++) {
	for (int i = 0; i < 40; i++) {
	    int key = key_maps[map][i];
	    out->mapping[map][i] = key > 0 ? native[key] : key;
	}
	out->mappings[map] = out->mapping[map];
    }
}

int host_key_from_native(const int *native, int scancode)
{
    for (int key = 1; key < HOST_KEY_COUNT; key++)
	if (native[key] >= 0 && native[key] == scancode)
	    return key;
    return HOST_KEY_NONE;
}
