static const uae_u8 *glyph(char ch)
{
	if (ch >= '0' && ch <= '9')
		return ldp_font[ch - '0'];
	if (ch >= 'a' && ch <= 'z')
		ch -= 'a' - 'A';
	if (ch >= 'A' && ch <= 'Z')
		return ldp_font[10 + ch - 'A'];
	return NULL;
}

void ldp_render(const char *text, int len, uae_u8 *buf, struct vidbuffer *vd,
	int dx, int dy, int mx, int my)
{
	const int bpp = vd->pixbytes;
	for (int i = 0; i < len; i++) {
		const uae_u8 *bits = glyph(text[i]);
		if (bits) {
			for (int x = 0; x < 5; x++) {
				for (int y = 0; y < 7; y++) {
					if (!(bits[x] & (1 << y)))
						continue;
					for (int yy = 0; yy < my; yy++) {
						const int py = dy + y * my + yy;
						if (py < 0 || py >= vd->inheight)
							continue;
						for (int xx = 0; xx < mx; xx++) {
							const int px = dx + x * mx + xx;
							if (px < 0 || px >= vd->inwidth)
								continue;
							memset(buf + py * vd->rowbytes + px * bpp, 0xff, bpp);
						}
					}
				}
			}
		}
		dx += 6 * mx;
	}
}
